#!/usr/bin/env bash
# Capture the exact, known-good training environment from the DGX node so the
# submission is reproducible. Run with the SAME interpreter used to train:
#     bash scripts/freeze_env.sh python3.9
# Then commit the generated requirements.lock.txt (authoritative over requirements.txt).
set -euo pipefail
PYBIN="${1:-python3.9}"
OUT="requirements.lock.txt"
{
  echo "# Authoritative lock generated by scripts/freeze_env.sh"
  echo "# interpreter: $("$PYBIN" --version 2>&1) | host: $(hostname)"
} > "$OUT"
"$PYBIN" -m pip freeze >> "$OUT"
echo "Wrote $OUT"
"$PYBIN" -c "import torch; print('torch', torch.__version__, '| cuda', torch.version.cuda)" || true
